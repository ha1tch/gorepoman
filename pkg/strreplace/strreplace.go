const (
	MarkerOpen  = "\u27e6"
	MarkerClose = "\u27e7"
)

var markerRe = regexp.MustCompile(regexp.QuoteMeta(MarkerOpen) + `RM:[a-z0-9]{16}` + regexp.QuoteMeta(MarkerClose))

// Refused carries a (class, message) pair -- every refusal in this
// package is one of these, surfaced to the caller via the returned
// result map's "error" field, never a bare error string.
type Refused struct {
	Cls     string
	Message string
}

func (r *Refused) Error() string { return fmt.Sprintf("%s: %s", r.Cls, r.Message) }

func refused(cls, format string, args ...interface{}) *Refused {
	return &Refused{Cls: cls, Message: fmt.Sprintf(format, args...)}
}

// ── payload decoding ────────────────────────────────────────────────

type opJSON struct {
	Op          *string  `json:"op"`
	File        string   `json:"file"`
	SearchB64   *string  `json:"search_b64"`
	ReplaceB64  *string  `json:"replace_b64"`
	Expect      *int     `json:"expect"`
	Roles       []string `json:"roles"`
	Occurrences []int    `json:"occurrences"`
	DryRun      *bool    `json:"dry_run"`
	SyntaxCheck *bool    `json:"syntax_check"`
	Count       *int     `json:"count"`
}

func (o opJSON) kind() string {
	if o.Op != nil {
		return *o.Op
	}
	return "sub"
}

type defaultsJSON struct {
	SyntaxCheck *bool `json:"syntax_check"`
	DryRun      *bool `json:"dry_run"`
}

type payloadJSON struct {
	V         *int         `json:"v"`
	Atomic    *bool        `json:"atomic"`
	Defaults  defaultsJSON `json:"defaults"`
	Ops       []opJSON     `json:"ops"`
	DryRunAll *bool        `json:"dry_run_all"`
}

func b64DecodeUTF8(s, what string) (string, error) {
	raw, err := base64.StdEncoding.DecodeString(s)
	if err != nil {
		return "", refused("invalid-utf8-payload", "%s: not valid base64 (%v)", what, err)
	}
	if !utf8.Valid(raw) {
		return "", refused("invalid-utf8-payload", "%s: base64 decodes but is not valid UTF-8", what)
	}
	return string(raw), nil
}

func isValidUTF8(b []byte) bool { return utf8.Valid(b) }

// readFileUTF8 reads a file and requires it decode as UTF-8, matching
// _read_file_utf8's own refusal class.
func readFileUTF8(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", refused("invalid-utf8-file", "%s: cannot read (%v)", path, err)
	}
	if !utf8.Valid(raw) {
		return "", refused("invalid-utf8-file", "%s: not valid UTF-8", path)
	}
	return string(raw), nil
}

// ── matching ─────────────────────────────────────────────────────────

// findAll returns every (possibly overlapping) byte offset at which
// search occurs in text, stepping by 1 after each hit -- the same
// overlap-permitting semantics pkg/ed's own `sub` command and Python's
// str.find(search, i+1) both use.
func findAll(text, search string) []int {
	if search == "" {
		return nil
	}
	var out []int
	i := strings.Index(text, search)
	for i != -1 {
		out = append(out, i)
		next := strings.Index(text[i+1:], search)
		if next == -1 {
			break
		}
		i = i + 1 + next
	}
	return out
}

// ── normalization (see the package doc comment's ADAPTATION note) ──

type diacritic struct {
	precomposed rune
	base        rune
	mark        rune
}

var diacriticsTable = buildDiacriticsTable()

func buildDiacriticsTable() []diacritic {
	type entry struct {
		base rune
		mark rune
	}
	// Latin-1 Supplement's accented letters, grouped by combining
	// mark -- covers the accented-Spanish-text case the original
	// docstring names directly (á é í ó ú ñ ü), plus the rest of
	// Latin-1's own accented range for broader Western-European
	// coverage at negligible extra cost.
	groups := map[rune][]rune{
		0x0300: {'a', 'e', 'i', 'o', 'u'},      // grave
		0x0301: {'a', 'e', 'i', 'o', 'u', 'y'}, // acute
		0x0302: {'a', 'e', 'i', 'o', 'u'},      // circumflex
		0x0303: {'a', 'n', 'o'},                // tilde
		0x0308: {'a', 'e', 'i', 'o', 'u', 'y'}, // diaeresis
		0x030a: {'a'},                          // ring above
		0x0327: {'c'},                          // cedilla
	}
	precomposedFor := map[[2]rune]rune{
		{'a', 0x0300}: 'à', {'a', 0x0301}: 'á', {'a', 0x0302}: 'â', {'a', 0x0303}: 'ã', {'a', 0x0308}: 'ä', {'a', 0x030a}: 'å',
		{'e', 0x0300}: 'è', {'e', 0x0301}: 'é', {'e', 0x0302}: 'ê', {'e', 0x0308}: 'ë',
		{'i', 0x0300}: 'ì', {'i', 0x0301}: 'í', {'i', 0x0302}: 'î', {'i', 0x0308}: 'ï',
		{'n', 0x0303}: 'ñ',
		{'o', 0x0300}: 'ò', {'o', 0x0301}: 'ó', {'o', 0x0302}: 'ô', {'o', 0x0303}: 'õ', {'o', 0x0308}: 'ö',
		{'u', 0x0300}: 'ù', {'u', 0x0301}: 'ú', {'u', 0x0302}: 'û', {'u', 0x0308}: 'ü',
		{'y', 0x0301}: 'ý', {'y', 0x0308}: 'ÿ',
		{'c', 0x0327}: 'ç',
	}
	var out []diacritic
	for mark, bases := range groups {
		for _, base := range bases {
			pre, ok := precomposedFor[[2]rune{base, mark}]
			if !ok {
				continue
			}
			out = append(out, diacritic{precomposed: pre, base: base, mark: rune(mark)})
			// Uppercase variant: base uppercased, precomposed uppercased.
			upperBase := []rune(strings.ToUpper(string(base)))[0]
			upperPre := []rune(strings.ToUpper(string(pre)))[0]
			out = append(out, diacritic{precomposed: upperPre, base: upperBase, mark: rune(mark)})
		}
	}
	return out
}

func nfcApprox(s string) string {
	runes := []rune(s)
	var out []rune
	i := 0
	for i < len(runes) {
		if i+1 < len(runes) {
			matched := false
			for _, d := range diacriticsTable {
				if runes[i] == d.base && runes[i+1] == d.mark {
					out = append(out, d.precomposed)
					i += 2
					matched = true
					break
				}
			}
			if matched {
				continue
			}
		}
		out = append(out, runes[i])
		i++
	}
	return string(out)
}

func nfdApprox(s string) string {
	runes := []rune(s)
	var out []rune
	for _, r := range runes {
		decomposed := false
		for _, d := range diacriticsTable {
			if r == d.precomposed {
				out = append(out, d.base, d.mark)
				decomposed = true
				break
			}
		}
		if !decomposed {
			out = append(out, r)
		}
	}
	return string(out)
}

// checkNormalization is only called when the raw search found zero
// matches. Reports, without guessing which is "correct", whether
// search would match under an NFC- or NFD-like transform -- see the
// package doc comment's ADAPTATION note for the scope of what this
// bounded table catches.
func checkNormalization(text, search string) error {
	hits := map[string]int{}
	if n := len(findAll(nfcApprox(text), nfcApprox(search))); n > 0 {
		hits["NFC"] = n
	}
	if n := len(findAll(nfdApprox(text), nfdApprox(search))); n > 0 {
		hits["NFD"] = n
	}
	if len(hits) == 0 {
		return nil
	}
	forms := make([]string, 0, len(hits))
	for f := range hits {
		forms = append(forms, f)
	}
	sort.Strings(forms)
	var parts []string
	for _, f := range forms {
		parts = append(parts, fmt.Sprintf("%d under %s", hits[f], f))
	}
	return refused("normalization-mismatch",
		"0 raw matches, but %s -- the file and the search payload disagree on Unicode "+
			"normalization form. Re-encode the search text from the file's own actual bytes "+
			"rather than resubmitting; do not auto-normalize.", strings.Join(parts, ", "))
}

// ── delimiter-integrity precheck ────────────────────────────────────

// contentRoles are roles where being INSIDE at the start of an edit
// means the entire replacement must stay inside throughout its own
// span -- escaping and re-entering with a BALANCED pair of delimiters
// (e.g. Go's own `hello" + injected + "` pattern) restores quote
// PARITY by the time the tail is reached, so a check that only
// samples text AFTER the replacement never sees it: both "before" and
// "after" are correctly inside the string, and the injected code in
// between is invisible to a check that never looks inside the
// replacement's own span.
var contentRoles = map[string]bool{
	"go-backtick-string": true, "go-dquote-string": true, "go-comment": true,
	"python-string": true, "python-comment": true,
	"json-string": true,
	"yaml-string": true, "yaml-comment": true,
	"shell-squote-string": true, "shell-dquote-string": true, "shell-backtick-string": true, "shell-comment": true,
	"md-fence": true, "md-inline-code": true,
}

var precheckOffsets = []int{0, 1, 2, 5, 10, 20, 40, 80, 160, 320, 640, 1280, 2560, 5120}

const precheckCap = 20000

// checkDelimiterIntegrity is a two-part differential re-classification,
// not a full parser.
//
// Part A (interior): only when the edit STARTS inside a content role
// (a string/comment of some kind) -- every offset within the
// replacement's own span must classify as that SAME role throughout.
// Any deviation means the replacement contains an unescaped delimiter
// that exits the enclosing construct, whether or not a later
// delimiter in the same replacement re-enters it (a balanced
// escape-and-reenter is exactly what this part exists to catch, and
// exactly what an after-only check cannot see).
//
// Part B (tail): for every edit regardless of starting role, the role
// at increasing distances after the replacement must match the role
// at the same distances after the original match -- catches an
// UNbalanced delimiter (opened, never closed within the replacement)
// that changes what everything downstream is classified as.
//
// Not caught by either part, by design, and left to the post-apply
// syntax validator instead: brace/paren/bracket balance, since no
// role here tracks nesting depth, only string/comment state.
func checkDelimiterIntegrity(path, original string, start, end int, replacement string) error {
	newText := original[:start] + replacement + original[end:]
	newPoint := start + len(replacement)
	startRole := roles.Classify(path, original, start)

	if contentRoles[startRole] {
		interiorLen := len(replacement)
		stride := 1
		if interiorLen > 2000 {
			stride = interiorLen / 2000
			if stride < 1 {
				stride = 1
			}
		}
		for off := 0; off < interiorLen; off += stride {
			role := roles.Classify(path, newText, start+off)
			if role != startRole {
				return refused("delimiter-break",
					"role at +%d char(s) INTO the replacement changed from %q (the role the edit "+
						"starts inside) to %q -- the replacement contains an unescaped delimiter for "+
						"this file's own format that exits the enclosing %s, whether or not it later "+
						"re-enters one. Escape the delimiter, or if exiting is genuinely intended, "+
						"split into separate ops so each one's own starting role matches its own content.",
					off, startRole, role, startRole)
			}
		}
	}

	origLen, newLen := len(original), len(newText)
	for _, off := range precheckOffsets {
		if off > precheckCap {
			break
		}
		oo, no := end+off, newPoint+off
		if oo >= origLen || no >= newLen {
			break
		}
		roleOrig := roles.Classify(path, original, oo)
		roleNew := roles.Classify(path, newText, no)
		if roleOrig != roleNew {
			return refused("delimiter-break",
				"role at +%d char(s) after the edit changed from %q to %q -- the replacement likely "+
					"contains an unescaped delimiter for this file's own format that changes what "+
					"encloses the text that follows. Escape it, or if the role change is genuinely "+
					"intended, make the edit with dry_run first and inspect the diff by hand.",
				off, roleOrig, roleNew)
		}
	}
	return nil
}

// ── markers ──────────────────────────────────────────────────────────

func genMarker(existingText string) string {
	for {
		var seed [16]byte
		_, _ = rand.Read(seed[:])
		h := sha256.Sum256(seed[:])
		b32 := strings.ToLower(strings.TrimRight(base32.StdEncoding.EncodeToString(h[:]), "="))
		marker := MarkerOpen + "RM:" + b32[:16] + MarkerClose
		if !strings.Contains(existingText, marker) {
			return marker
		}
	}
}

