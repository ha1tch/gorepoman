// Package strreplace implements format-aware, journaled, base64-payload
// text substitution -- translated from repoman/str_replace_extended.py.
//
// Built to retire the failure class that direct str_replace/sed/awk
// substitution invites: content passing through a shell/argv quoting
// layer before it reaches disk, and edits landing without ever
// checking whether they broke the file's own syntax. Two recorded
// incidents in this project's own session history motivated it
// directly: a replacement's escape sequences (\n, \t) silently taken
// literally by bash's $'...' quoting because an apostrophe inside the
// content closed the quote early, and a duplicated line produced by a
// replacement whose own leading text overlapped its anchor span,
// applied faithfully by a tool with no way to notice.
//
// NEVER accepts search/replace text as CLI arguments. The payload is
// JSON, read from stdin or a file, with all search/replace content
// carried as base64 of raw UTF-8 bytes -- so a backtick, an
// apostrophe, a newline, or any other character with shell meaning
// can never be reinterpreted before it reaches this tool.
//
// CLI:
//
//	repoman strreplace apply [-|payload.json]
//	repoman strreplace selftest
//
// Library:
//
//	result := strreplace.ApplyPayloadJSON(raw)   // []byte in, map out
//
// Payload schema (v1), one JSON document:
//
//	{
//	  "v": 1,
//	  "atomic": true,                    // default true; see below
//	  "defaults": {"syntax_check": true, "dry_run": false},
//	  "ops": [
//	    {
//	      "op": "sub",                   // default "sub" if omitted
//	      "file": "path/to/file",
//	      "search_b64": "<base64 of raw utf-8 search text>",
//	      "replace_b64": "<base64 of raw utf-8 replacement text>",
//	      "expect": 1,                   // REQUIRED, no default -- exact
//	                                      // match count, or the op refuses
//	      "roles": ["go-code"],          // REQUIRED -- every match's
//	                                      // classified role must be one of
//	                                      // these, or the op refuses with
//	                                      // the real census printed
//	      "occurrences": null,           // null = all matches (requires a
//	                                      // uniform role); [2, 4] = only
//	                                      // those 1-indexed matches
//	      "dry_run": false,              // overrides defaults.dry_run
//	      "syntax_check": true           // overrides defaults.syntax_check
//	    },
//	    {"op": "gen_markers", "file": "path/to/file", "count": 2},
//	    {"op": "sweep_markers", "file": "path/to/file"}
//	  ]
//	}
//
// atomic (default true): when multiple ops are staged, either every
// op in the payload applies or none do. Ops targeting the same file
// apply in listed order against each other's in-memory result
// (mirroring pkg/ed's own per-file staged-write discipline);
// syntax-check runs once per touched file against its final staged
// content. atomic:false applies ops independently, collecting
// successes and failures separately -- use only when a later op's
// failure genuinely should not undo an earlier one.
//
// Refusal classes (op-level; exit 1 overall if any refuse under
// atomic mode, nothing written; each reason appears on stderr AND in
// the JSON result's own "error" field):
//
//	invalid-utf8-file        file does not decode as UTF-8
//	invalid-utf8-payload     search_b64/replace_b64 does not decode
//	normalization-mismatch   0 raw matches, but N would match under a
//	                          different Unicode normalization form
//	count-mismatch           occurrences found != expect
//	role-mismatch            census is not a subset of the asserted
//	                          roles; real census printed
//	delimiter-break          the edit changes the syntactic role of text
//	                          immediately following it (a differential
//	                          re-classification, not a full parser) --
//	                          catches unescaped delimiters landing inside
//	                          string/comment context
//	syntax-check-failed      post-apply format validator failed; the
//	                          write is rolled back before this returns
//
// Every genuinely-applied op (not dry-run, not marker ops) is
// recorded in pkg/ed's own journal (.ed-journal.json) via ed.Record --
// one undo history for both tools regardless of which one made a
// given edit. `repoman ed mark` / `repoman ed undo` / `repoman ed log`
// all see these edits too.
//
// Markers (gen_markers / sweep_markers): for workflows that stage a
// change in two steps (insert a marker, later replace between
// markers), markers are generated by this tool, never supplied by the
// caller as literal text -- collision-checked against the live file
// content before being returned, using the U+27E6/U+27E7 MATHEMATICAL
// WHITE SQUARE BRACKET pair, valid UTF-8, printable, and not syntax in
// any format this tool validates. sweep_markers removes every marker
// this tool's own format ever produced, recognisable by a fixed
// prefix, so a marker generated in a crashed or abandoned session
// cannot silently survive.
//
// ADAPTATION FROM THE PYTHON ORIGINAL, documented once here rather
// than scattered: _check_normalization used Python's stdlib
// unicodedata module (full Unicode NFC/NFD normalization). Go's
// standard library has no equivalent, and golang.org/x/text (which
// does) is a third-party module this project's zero-dependency
// convention deliberately avoids and this sandbox's network policy
// cannot fetch cleanly regardless. checkNormalization below instead
// implements a bounded precomposed<->decomposed table for the Latin-1
// Supplement accented letters -- exactly the "accented Spanish text"
// case the original docstring names as the live concern. Text using
// other scripts' composed/decomposed forms will not be caught by this
// check; normalization-mismatch simply won't fire for those, the same
// "documented gap, not silently wrong" pattern pkg/roles already uses
// for its own YAML block-scalar and shell-heredoc limitations.
